import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const errors=[];const base=process.env.QA_URL||'http://localhost:5173/';
const ready=async page=>{page.setDefaultTimeout(90000);page.on('pageerror',e=>errors.push(e.message));await page.goto(base,{waitUntil:'networkidle'});await page.waitForFunction(()=>!!window.frontier?.view);await page.waitForFunction(()=>{const button=document.querySelector('#landing [data-mode="skirmish"]');return !!button&&!button.disabled;});};
fs.mkdirSync('artifacts',{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await ready(page);
await page.screenshot({path:'artifacts/desktop-menu.png'});
await page.locator('[data-mode="skirmish"]').click();
await page.locator('[data-start="skirmish"]').click();
await page.waitForFunction(()=>frontier.playing);
await page.waitForTimeout(1500);
await page.evaluate(()=>frontier.action('home'));
await page.screenshot({path:'artifacts/desktop-game.png'});
await page.locator('.command-buttons [data-action=build]').click();
await page.waitForFunction(()=>!document.querySelector('#build-panel').classList.contains('hidden'));
await page.screenshot({path:'artifacts/desktop-build.png'});
const desktop=await page.evaluate(()=>({playing:frontier.playing,entities:frontier.sim.entities.length,canvas:!!document.querySelector('#world canvas'),buildPanel:!document.querySelector('#build-panel').classList.contains('hidden'),calls:frontier.view.renderer.info.render.calls,triangles:frontier.view.renderer.info.render.triangles}));
assert.equal(desktop.playing,true);assert.ok(desktop.entities>0&&desktop.canvas&&desktop.buildPanel);await page.close();
const mobile=await browser.newPage({viewport:{width:844,height:390},isMobile:true,hasTouch:true,deviceScaleFactor:2});
await ready(mobile);
await mobile.screenshot({path:'artifacts/mobile-menu.png'});
await mobile.locator('[data-mode="skirmish"]').tap();await mobile.locator('[data-start="skirmish"]').tap();
await mobile.waitForFunction(()=>frontier.playing);
await mobile.waitForTimeout(1000);await mobile.evaluate(()=>frontier.action('home'));await mobile.screenshot({path:'artifacts/mobile-game.png'});
await mobile.locator('.command-buttons [data-action=build]').tap();await mobile.screenshot({path:'artifacts/mobile-build.png'});
await mobile.waitForFunction(()=>!document.querySelector('#build-panel').classList.contains('hidden'));
const phone=await mobile.evaluate(()=>({playing:frontier.playing,entities:frontier.sim.entities.length,canvas:!!document.querySelector('#world canvas'),width:innerWidth,height:innerHeight,scroll:document.documentElement.scrollWidth>innerWidth,buildPanel:!document.querySelector('#build-panel').classList.contains('hidden'),calls:frontier.view.renderer.info.render.calls}));
assert.equal(phone.playing,true);assert.ok(phone.entities>0&&phone.canvas&&phone.buildPanel);assert.equal(phone.scroll,false);assert.deepEqual(errors,[]);
console.log(JSON.stringify({desktop,phone,errors},null,2));await browser.close();
